/**
 * The translation layer: a dictionary and a `t(key)` lookup, nothing more.
 *
 * The surface is deliberately small — the chrome strings (top bar, sidebar, list head, dialog
 * titles and buttons, the toasts these components raise). Article content is never translated.
 *
 * Reactivity: `t()` reads `prefs.language`, and `prefs` is rune-backed state from
 * `prefs.svelte.ts`. A component that calls `t()` while rendering therefore re-renders when the
 * `#rd-lang` select changes, without any subscription machinery here. The choice is persisted
 * under the reference reader's own `feeddi-lang` localStorage key, in `prefs.svelte.ts`.
 */

