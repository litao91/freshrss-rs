const DICTS: Record<Language, Record<string, string>> = { en, tr };

/**
 * Translates a key.
 *
 * Resolution order: the current language, then English, then `fallback`, then the key itself.
 * The English hop is what lets a partially translated language degrade to English per string
 * instead of showing raw keys; the fallback is how `HelpDialog` renders bindings that no
 * dictionary knows yet, straight from `keys.ts`.
 *
 * Reading `prefs.language` here — inside the caller's render — is what makes translations
 * reactive; see the module note.
 */
export function t(key: string, fallback?: string): string {
  return DICTS[prefs.language][key] ?? en[key] ?? fallback ?? key;
}

/** `t()` with `{name}` placeholders filled in, the same convention the reference reader uses. */
export function tf(key: string, params: Record<string, string | number>, fallback?: string): string {
  return t(key, fallback).replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match,
  );
}
