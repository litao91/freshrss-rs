#!/usr/bin/env python3
"""Regenerate web/src/fonts.css from a copy of Feeddi's published stylesheet.

The reader's typography must match Feeddi exactly, including the per-subset `unicode-range`
declarations that let the browser download only the slices it needs. Rather than transcribing
22 `@font-face` rules by hand, this copies them verbatim from Feeddi's own CSS and rewrites only
the URL prefix to the locally vendored copies.

Usage:
    python3 tools/gen-fonts.py /path/to/Feeddi.min.css

The woff2 files themselves live in web/public/vendor/fonts/ and were fetched from
https://feeddi.com/_content/Feeddi.Reader.UI/fonts/feeddi/<name>.woff2
"""

import os
import re
import sys

FONT_URL_PREFIX = "/_content/Feeddi.Reader.UI/fonts/feeddi/"
VENDORED_PREFIX = "/vendor/fonts/"
VENDOR_DIR = "web/public/vendor/fonts"
OUTPUT = "web/src/fonts.css"

HEADER = """/* Generated by tools/gen-fonts.py from Feeddi's published stylesheet.
 *
 * The @font-face rules below are copied verbatim -- including the unicode-range subsets -- so
 * the reader's typography matches Feeddi exactly. Only the URL prefix is rewritten to point at
 * the locally vendored copies in web/public/vendor/fonts/.
 *
 * Do not edit by hand.
 */

"""


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2

    source = open(sys.argv[1], encoding="utf-8", errors="replace").read()
    blocks = re.findall(r"@font-face\{[^}]*\}", source)

    keep: list[str] = []
    seen: set[tuple] = set()
    for block in blocks:
        if FONT_URL_PREFIX not in block:
            continue
        rewritten = block.replace(FONT_URL_PREFIX, VENDORED_PREFIX)
        family = re.search(r'font-family:"([^"]+)"', rewritten).group(1)
        style = re.search(r"font-style:(\w+)", rewritten).group(1)
        weight = re.search(r"font-weight:([\d ]+)", rewritten).group(1)
        filename = re.search(r"/vendor/fonts/([\w.-]+)", rewritten).group(1)

        # Feeddi repeats each face per weight; identical (family, style, weight, file) tuples
        # are duplicates and would only bloat the sheet.
        key = (family, style, weight, filename)
        if key in seen:
            continue
        seen.add(key)
        keep.append(rewritten)

    missing = [
        f
        for f in (re.search(r"/vendor/fonts/([\w.-]+)", b).group(1) for b in keep)
        if not os.path.exists(os.path.join(VENDOR_DIR, f))
    ]
    if missing:
        print(f"error: vendored font files missing: {sorted(set(missing))}", file=sys.stderr)
        return 1

    with open(OUTPUT, "w", encoding="utf-8") as out:
        out.write(HEADER + "\n\n".join(keep) + "\n")

    print(f"wrote {OUTPUT}: {len(keep)} faces")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
